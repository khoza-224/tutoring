/* ---------- Output and input helpers ---------- */

// Escape output (XSS protection)
function e($value): string
{
    return htmlspecialchars((string)$value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

function post(string $key, bool $trim = true): string
{
    $v = $_POST[$key] ?? '';
    if (!is_string($v)) return '';
    return $trim ? trim($v) : $v;
}

function req(string $key): string
{
    $v = $_GET[$key] ?? '';
    return is_string($v) ? trim($v) : '';
}

function page_start(string $title, bool $wide = false): void
{
    echo '<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8">'
       . '<meta name="viewport" content="width=device-width, initial-scale=1.0">'
       . '<title>' . e($title) . ' | Tutoring System</title>'
       . '<link rel="stylesheet" href="style.css"></head><body>'
       . '<header><nav><a href="dashboard.php">Dashboard</a><a href="logout.php">Logout</a></nav></header>'
       . '<main' . ($wide ? ' class="wide"' : '') . '>';
}

function page_end(): void
{
    echo '</main></body></html>';
}

function message_page(string $title, string $message, bool $ok = false, string $back = 'javascript:history.back()'): void
{
    page_start($title);
    echo '<h1>' . e($title) . '</h1>';
    echo '<p class="' . ($ok ? 'ok' : 'error') . '">' . e($message) . '</p>';
    echo '<p><a href="' . e($back) . '">Continue</a></p>';
    page_end();
    exit;
}

function render_table(array $rows): void
{
    if (!$rows) {
        echo '<p>No records found.</p>';
        return;
    }
    echo '<table><thead><tr>';
    foreach (array_keys($rows[0]) as $col) {
        echo '<th>' . e(str_replace('_', ' ', $col)) . '</th>';
    }
    echo '</tr></thead><tbody>';
    foreach ($rows as $row) {
        echo '<tr>';
        foreach ($row as $cell) {
            echo '<td>' . e($cell) . '</td>';
        }
        echo '</tr>';
    }
    echo '</tbody></table>';
}

function post_only(): void
{
    if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
        http_response_code(405);
        message_page('Invalid request', 'This page only accepts form submissions.');
    }
    verify_same_origin();
}

/* ---------- CSRF tokens (for pages generated by PHP) ---------- */

function csrf_token(): string
{
    if (empty($_SESSION['csrf'])) {
        $_SESSION['csrf'] = bin2hex(random_bytes(32));
    }
    return $_SESSION['csrf'];
}

function csrf_field(): string
{
    return '<input type="hidden" name="csrf" value="' . e(csrf_token()) . '">';
}

function csrf_check(): void
{
    $token = $_POST['csrf'] ?? '';
    if (!is_string($token) || !hash_equals($_SESSION['csrf'] ?? '', $token)) {
        http_response_code(400);
        message_page('Invalid request', 'Your security token is missing or has expired. Reload the page and try again.');
    }
}

/* ---------- Validation helpers ---------- */

function parse_date(string $s): ?DateTime
{
    $d = DateTime::createFromFormat('Y-m-d', $s);
    return ($d && $d->format('Y-m-d') === $s) ? $d : null;
}

// Returns "HH:MM:00" or null
function parse_time(string $s): ?string
{
    return preg_match('/^([01]\d|2[0-3]):[0-5]\d(:00)?$/', $s) ? substr($s, 0, 5) . ':00' : null;
}

// Business rule: sessions run Monday to Friday only
function is_weekday(DateTime $d): bool
{
    return (int)$d->format('N') <= 5;
}

function strong_password(string $p): bool
{
    return strlen($p) >= 8 && strlen($p) <= 72
        && preg_match('/[a-z]/', $p) && preg_match('/[A-Z]/', $p) && preg_match('/\d/', $p);
}

/* ---------- Scheduling rules shared by booking and admin scripts ---------- */

// Does the tutor already have a non-cancelled session overlapping this time?
function tutor_conflicts(PDO $pdo, int $tutorId, string $date, string $start, string $end, int $excludeBooking = 0): bool
{
    $st = $pdo->prepare(
        "SELECT 1 FROM bookings
         WHERE tutor_id = ? AND session_date = ? AND booking_id <> ?
           AND status <> 'cancelled' AND start_time < ? AND end_time > ? LIMIT 1"
    );
    $st->execute([$tutorId, $date, $excludeBooking, $end, $start]);
    return (bool)$st->fetchColumn();
}

// Does the tutor teach the programme AND have an availability slot covering the time?
function tutor_available(PDO $pdo, int $tutorId, int $programmeId, string $dayName, string $start, string $end): bool
{
    $st = $pdo->prepare(
        "SELECT 1 FROM tutor_programmes tp
         JOIN tutor_availability ta ON ta.tutor_id = tp.tutor_id
         WHERE tp.tutor_id = ? AND tp.programme_id = ?
           AND ta.day_of_week = ? AND ta.start_time <= ? AND ta.end_time >= ? LIMIT 1"
    );
    $st->execute([$tutorId, $programmeId, $dayName, $start, $end]);
    return (bool)$st->fetchColumn();
}

/* ---------- Notifications: student, assigned tutor and every administrator ---------- */

function notify_booking(PDO $pdo, int $bookingId, string $event): void
{
    $words = [
        'confirmed'  => 'confirmed',
        'cancelled'  => 'cancelled',
        'completed'  => 'marked as completed',
        'reassigned' => 'reassigned to a new tutor',
    ];
    $what = $words[$event] ?? $event;

    $st = $pdo->prepare(
        "SELECT b.session_date, b.start_time,
                s.email AS student_email, CONCAT(s.first_name, ' ', s.last_name) AS student_name,
                t.email AS tutor_email, t.full_name AS tutor_name, p.programme_name
         FROM bookings b
         JOIN enrolments e ON e.enrolment_id = b.enrolment_id
         JOIN students s   ON s.student_id   = e.student_id
         JOIN programmes p ON p.programme_id = e.programme_id
         JOIN tutors t     ON t.tutor_id     = b.tutor_id
         WHERE b.booking_id = ?"
    );
    $st->execute([$bookingId]);
    $b = $st->fetch();
    if (!$b) return;

    $when = $b['session_date'] . ' at ' . substr($b['start_time'], 0, 5);
    $rows = [
        ['student', $b['student_email'],
            "Your {$b['programme_name']} session on $when with {$b['tutor_name']} has been $what."],
        ['tutor', $b['tutor_email'],
            "Session #$bookingId ({$b['programme_name']}, $when, student {$b['student_name']}) has been $what."],
    ];
    foreach ($pdo->query('SELECT email FROM administrators')->fetchAll() as $a) {
        $rows[] = ['admin', $a['email'],
            "Booking #$bookingId ({$b['programme_name']}, $when) has been $what."];
    }

    $ins = $pdo->prepare(
        'INSERT INTO notifications (booking_id, recipient_role, recipient_email, message) VALUES (?, ?, ?, ?)'
    );
    foreach ($rows as [$role, $email, $msg]) {
        $ins->execute([$bookingId, $role, $email, mb_substr($msg, 0, 255)]);
        // On a live server you could also call mail($email, 'Tutoring booking update', $msg);
    }
}